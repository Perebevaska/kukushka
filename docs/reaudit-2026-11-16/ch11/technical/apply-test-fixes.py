blocks = list(re.finditer(r'(?ms)^::: quiz\b.*?^:::', s))
changes = {}

def edit(number, replacements):
    text = blocks[number - 1].group()
    for before, after in replacements:
        assert text.count(before) == 1, (number, before)
        text = text.replace(before, after)
    changes[number] = text

